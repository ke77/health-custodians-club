'use server'

import { gradeScaleOf } from '@/lib/config/application'
import { hashedIp } from '@/lib/actions/request-meta'
import { rateLimit } from '@/lib/actions/rate-limit'
import { verifyTurnstile } from '@/lib/actions/turnstile'
import { getSettings, windowOpen } from '@/lib/data/settings'
import { sendEmail } from '@/lib/email/resend'
import { adminNewApplication, applicationReceived } from '@/lib/email/templates/application'
import { createServiceClient } from '@/lib/supabase/service'
import type { Database } from '@/lib/supabase/types'
import { parseApplication } from '@/lib/validation/application'
import type { Application } from '@/lib/validation/application'

export type SubmitResult =
  | { ok: true; reference: string }
  | { ok: false; reason: 'invalid'; fields: string[] }
  | { ok: false; reason: 'closed' | 'duplicate' | 'rate_limited' | 'turnstile' | 'error' }

type ApplicationInsert = Database['public']['Tables']['applications']['Insert']
type Region = Database['public']['Enums']['region']

// the parsed, normalised answers become a database row. the reference number is generated by the database.
function toInsert(a: Application, cohort: string, ipHash: string | null): ApplicationInsert {
  const scale = gradeScaleOf(a.grade)
  return {
    cohort,
    full_name: a.fullName,
    email: a.email,
    phone: a.phone,
    whatsapp: a.whatsappSame ? a.phone : a.whatsapp,
    gender: a.gender === '' ? null : a.gender,
    date_of_birth: a.dateOfBirth,
    level: Number(a.level),
    institution: a.institution,
    institution_other: a.institution === 'Other' ? a.institutionOther : null,
    programme: a.programme,
    programme_other: a.programme === 'Other health-related' ? a.programmeOther : null,
    student_id: a.studentId,
    cgpa: scale === 'cgpa' ? Number(a.grade) : null,
    cwa: scale === 'cwa' ? Number(a.grade) : null,
    // the schema validates these against the 16 region names, which are exactly the enum values
    home_region: a.homeRegion as Region,
    current_region: a.currentRegion as Region,
    languages: a.languages,
    language_other: a.languages.some((l) => l.language === 'Other') ? a.languageOther : null,
    interests: a.interests,
    leadership_interest: a.leadership,
    hours_per_month: Number(a.hoursPerMonth),
    committed: a.committed === 'yes',
    skills: a.skills,
    answer_motivation: a.answerMotivation,
    answer_health_gap: a.answerHealthGap,
    answer_skills: a.answerSkills,
    answer_balance: a.answerBalance,
    heard_about: a.heardAbout,
    heard_about_other: a.heardAbout === 'Other' ? a.heardAboutOther : null,
    consent_at: new Date().toISOString(),
    ip_hash: ipHash,
  }
}

/*
  pipeline from docs/04-application-form.md, cheapest checks first: window, honeypot, Turnstile, rate limit,
  validation, insert (the unique index rejects a second application per email per cohort), then emails.
  an email failure never fails the submission: the row is already saved.
*/
export async function submitApplication(input: unknown, token?: string): Promise<SubmitResult> {
  const settings = await getSettings()
  if (!windowOpen(settings)) return { ok: false, reason: 'closed' }

  const parsed = parseApplication(input)
  if (!parsed.success) {
    // a filled honeypot fails validation too; bots get the same answer as anyone with a bad field
    const fields = [...new Set(parsed.issues.map((i) => String(i.path[0])))]
    return { ok: false, reason: 'invalid', fields }
  }

  const ipHash = await hashedIp()
  if (!(await verifyTurnstile(token, ipHash))) return { ok: false, reason: 'turnstile' }

  const limitKey = ipHash ?? parsed.data.email
  const limited = await rateLimit(limitKey, 'application', 5, 60 * 60)
  if (!limited.ok) return { ok: false, reason: 'rate_limited' }

  const supabase = createServiceClient()
  const { data, error } = await supabase
    .from('applications')
    .insert(toInsert(parsed.data, settings.currentCohort, ipHash))
    .select('reference')
    .single()

  if (error) {
    if (error.code === '23505') return { ok: false, reason: 'duplicate' }
    console.error('application insert failed', error.code, error.message)
    return { ok: false, reason: 'error' }
  }

  await sendApplicationEmails(parsed.data, data.reference)
  return { ok: true, reference: data.reference }
}

async function sendApplicationEmails(a: Application, reference: string) {
  const siteUrl = process.env.NEXT_PUBLIC_SITE_URL ?? ''
  try {
    await sendEmail({ to: a.email, email: applicationReceived({ name: a.fullName, reference, email: a.email }) })
    const adminTo = process.env.ADMIN_NOTIFY_EMAIL
    if (adminTo) {
      await sendEmail({
        to: adminTo,
        email: adminNewApplication({
          application: {
            reference,
            full_name: a.fullName,
            programme: a.programme,
            institution: a.institution === 'Other' ? a.institutionOther : a.institution,
            level: Number(a.level),
            current_region: a.currentRegion as Region,
          },
          dashboardUrl: `${siteUrl}/admin/applications`,
        }),
      })
    }
  } catch (err) {
    // the application is saved; a mail problem must not surface as a failed submission
    console.error('application emails failed', err instanceof Error ? err.message : err)
  }
}
